export async function initializeDatabaseDefaults() {
  try {
    const settingsRef = doc(db, 'siteSettings', 'config');
    const settingsSnap = await getDoc(settingsRef).catch(() => null);
    if (!settingsSnap || !settingsSnap.exists()) {
      await setDoc(settingsRef, defaultSiteSettings).catch(() => {});
    }

    const navratriCol = collection(db, 'navratri');
    const navratriSnap = await getDocs(navratriCol).catch(() => null);
    
    if (!navratriSnap || navratriSnap.empty || navratriSnap.size < 9) {
      for (const day of defaultNavratriDays) {
        await setDoc(doc(db, 'navratri', `day_${day.dayNumber}`), day, { merge: true }).catch(() => {});
      }
    } else {
      // Ensure existing days have complete katha/mantra/pujanVidhi if missing
      for (const day of defaultNavratriDays) {
        await setDoc(doc(db, 'navratri', `day_${day.dayNumber}`), day, { merge: true }).catch(() => {});
      }
    }

    const noticesCol = collection(db, 'notices');
    const noticesSnap = await getDocs(noticesCol).catch(() => null);
    if (!noticesSnap || noticesSnap.empty) {
      await addDoc(noticesCol, {
        title: 'नवरात्रि महोत्सव 2026 विशेष आमंत्रण',
        content: 'माँ जगदंबा स्थान में चैत्र नवरात्रि महोत्सव का भव्य आयोजन किया जा रहा है। सभी भक्तगण सपरिवार आमंत्रित हैं।',
        priority: 'High',
        publishDate: '2026-03-01',
        expiryDate: '2026-04-15',
        isPinned: true,
        isActive: true,
        createdAt: new Date()
      }).catch(() => {});
      await addDoc(noticesCol, {
        title: 'दैनिक अन्नदान एवं भंडारा सूचना',
        content: 'मंदिर परिसर में प्रतिदिन दोपहर 12 बजे से विशाल भंडारे का आयोजन होता है।',
        priority: 'Normal',
        publishDate: '2026-01-01',
        expiryDate: '2026-12-31',
        isPinned: false,
        isActive: true,
        createdAt: new Date()
      }).catch(() => {});
    }
  } catch (err: any) {
    if (err?.code === 'failed-precondition' || err?.message?.includes('offline')) {
      console.log('Database operating in offline mode.');
    } else {
      console.warn('Database defaults initialization note:', err?.message || err);
    }
  }
}
